/* section: types */
typedef enum {
	LOG_STDERR_STREAM,
	LOG_STDERR_PIPE,
	LOG_STDERR_SOCKET,
	LOG_STDERR_UNAVAILABLE
} log_stderr_sink;

/* section: global variables */
static log_stderr_sink stderr_sink;

/* section: functions (local) */
static void gettime(char *target, size_t target_size) {
	time_t timestamp = time(NULL);
	struct tm tm_local;
	target[0] = '\0';
	if (localtime_r(&timestamp, &tm_local) == NULL) {
		return;
	}
	size_t target_length = strftime(target, target_size, "%Y-%m-%d %H:%M:%S UTC%z", &tm_local);
	if (target_length < 5 || target_length + 1 >= target_size || (target[target_length - 5] != '+' && target[target_length - 5] != '-')) {
		target[0] = '\0';
		return;
	}
	/* strftime formats %z as +hhmm; insert the colon used by the log format. */
	memmove(target + target_length - 1, target + target_length - 2, 3);
	target[target_length - 2] = ':';
}

/* Opens filename append-only and safely: the final path component must not be a symlink, only regular files pass, and a FIFO without a reader fails instead of blocking. The caller owns the descriptor. */
static int log_fd_open(const char *filename) {
	int fd;
	struct stat file_status;
	if (filename == NULL) {
		errno = EINVAL;
		return -1;
	}
	fd = open(filename, O_WRONLY | O_APPEND | O_CREAT | O_CLOEXEC | O_NOFOLLOW | O_NONBLOCK, 0666);
	if (fd == -1) {
		return -1;
	}
	if (fstat(fd, &file_status) == -1) {
		int saved_errno = errno;
		close(fd);
		errno = saved_errno;
		return -1;
	}
	if (!S_ISREG(file_status.st_mode)) {
		close(fd);
		errno = EIO;
		return -1;
	}
	return fd;
}

static bool log_stderr_write(bool noprefix, const char *message, mksys_line_end line_end) {
	const char *prefix = noprefix ? "" : "[CRIT] ";
	const char *ending = line_end == MKSYS_PARAGRAPH_END ? "\n\n" : "\n";
	if (stderr_sink == LOG_STDERR_STREAM) {
		return fprintf(stderr, "%s%s%s", prefix, message, ending) >= 0;
	}
	struct iovec parts[] = {
		{ (void *)prefix, strlen(prefix) },
		{ (void *)message, strlen(message) },
		{ (void *)ending, strlen(ending) }
	};
	ssize_t written;
	if (stderr_sink == LOG_STDERR_SOCKET) {
		struct msghdr header = { .msg_iov = parts, .msg_iovlen = 3 };
		written = sendmsg(STDERR_FILENO, &header, MSG_DONTWAIT | MSG_NOSIGNAL);
	} else if (stderr_sink == LOG_STDERR_PIPE) {
		/* A pipe has no MSG_NOSIGNAL. Consume only a SIGPIPE generated by this write. */
		sigset_t mask, previous, pending;
		sigemptyset(&mask);
		sigaddset(&mask, SIGPIPE);
		if (sigprocmask(SIG_BLOCK, &mask, &previous) == -1) {
			return false;
		}
		written = -1;
		if (sigpending(&pending) == 0) {
			written = writev(STDERR_FILENO, parts, 3);
			if (written == -1 && errno == EPIPE && !sigismember(&pending, SIGPIPE)) {
				struct timespec zero = { 0 };
				while (sigtimedwait(&mask, NULL, &zero) == -1 && errno == EINTR) {}
			}
		}
		sigprocmask(SIG_SETMASK, &previous, NULL);
	} else {
		return false;
	}
	return written >= 0 && (size_t)written == parts[0].iov_len + parts[1].iov_len + parts[2].iov_len;
}

static int log_write(bool noprefix, const char *logfile, uint8_t maxlevel, mksys_level msglevel, mksys_line_end line_end, const char *message) {
	if (message == NULL) {
		message = "";
	}
	bool failed = false;
	char level_str[8];
	if (msglevel > maxlevel) {
		return 0;
	}
	memset(level_str, 0, 8);
	switch (msglevel) {
		case MKSYS_LEVEL_CRITICAL:
			strcpy(level_str, "CRIT");
			break;
		case MKSYS_LEVEL_WARNING:
			strcpy(level_str, "WARN");
			break;
		default:
			strcpy(level_str, "INFO");
			break;
	}
	if (strcmp(logfile, MKSYS_NOLOGFILE) != 0) {
		char time_str[32];
		gettime(time_str, sizeof(time_str));
		int logfd = log_fd_open(logfile);
		if (logfd == -1) {
			failed = true;
		} else {
			FILE *log_stream = fdopen(logfd, "a");
			if (log_stream == NULL) {
				close(logfd);
				failed = true;
			} else {
				if (noprefix == MKSYS_PREFIX_ON && fprintf(log_stream, "[%s] [%s] ", time_str, level_str) < 0) {
					failed = true;
				}
				if (fprintf(log_stream, "%s\n", message) < 0) {
					failed = true;
				}
				if (fclose(log_stream) != 0) {
					failed = true;
				}
			}
		}
	}
	if (noprefix == MKSYS_PREFIX_OFF && !isatty(STDOUT_FILENO)) {
		return failed ? 1 : 0;
	}
	if (msglevel == MKSYS_LEVEL_CRITICAL) {
		if (!log_stderr_write(noprefix, message, line_end)) {
			failed = true;
		}
	} else {
		if (noprefix == MKSYS_PREFIX_ON && fprintf(stdout, "[%s] ", level_str) < 0) {
			failed = true;
		}
		if (fprintf(stdout, line_end == MKSYS_PARAGRAPH_END ? "%s\n\n" : "%s\n", message) < 0) {
			failed = true;
		}
	}
	return failed ? 1 : 0;
}

/* section: functions (exported) */
int log_file_validate(const char *filename) {
	/* The safe open creates and keeps an empty regular file in place; the previous create-then-unlink probe left a symlink swap window. */
	int fd = log_fd_open(filename);
	if (fd == -1) {
		return -1;
	}
	return close(fd);
}

void log_stderr_prepare(void) {
	struct stat status;
	if (fstat(STDERR_FILENO, &status) == -1) {
		stderr_sink = LOG_STDERR_UNAVAILABLE;
	} else if (S_ISSOCK(status.st_mode)) {
		stderr_sink = LOG_STDERR_SOCKET;
	} else if (S_ISFIFO(status.st_mode)) {
		/* Reopen the pipe so O_NONBLOCK does not change the supervisor's file description. */
		int fd = open("/proc/self/fd/2", O_WRONLY | O_NONBLOCK | O_CLOEXEC);
		stderr_sink = fd != -1 && dup2(fd, STDERR_FILENO) != -1 ? LOG_STDERR_PIPE : LOG_STDERR_UNAVAILABLE;
		if (fd != -1) {
			close(fd);
		}
	} else {
		stderr_sink = LOG_STDERR_STREAM;
	}
}

int mksysmsg(bool noprefix, const char *logfile, uint8_t maxlevel, mksys_level msglevel, mksys_line_end line_end, const char *format, ...) {
	char format_line[BUFSIZ];
	char rendered[BUFSIZ];
	char escaped[BUFSIZ * 4 + 1];
	va_list varlist;
	size_t format_length = 0;
	if (format == NULL) {
		format = "";
	}
	/* A newline in a format never reaches the output; the line end comes from line_end instead. */
	while (format_length + 1 < sizeof(format_line) && format[format_length] != '\0' && format[format_length] != '\n') {
		format_line[format_length] = format[format_length];
		format_length++;
	}
	format_line[format_length] = '\0';
	va_start(varlist, format);
	int rendered_length = vsnprintf(rendered, sizeof(rendered), format_line, varlist);
	va_end(varlist);
	if (rendered_length < 0) {
		rendered_length = 0;
	}
	size_t rendered_size = (size_t)rendered_length;
	if (rendered_size >= sizeof(rendered)) {
		rendered_size = sizeof(rendered) - 1;
	}
	return log_write(noprefix, logfile, maxlevel, msglevel, line_end, escape_default(escaped, sizeof(escaped), rendered, rendered_size));
}
